/** Все русские ключи словаря — для проверки полноты переводов. */
export const DICT_KEYS = Object.keys(D);

let current: Lang = 'ru';

export const isLang = (v: unknown): v is Lang => v === 'ru' || v === 'en' || v === 'pl';

export function setLang(lang: Lang) {
  current = lang;
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export const getLang = () => current;

/** Язык браузера как предложение по умолчанию. */
export function detectLang(): Lang {
  const list = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  for (const l of list) {
    const code = l.slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return 'en';
}

export function tr(ru: string): string {
  if (current === 'ru') return ru;
  const e = D[ru];
  return e ? e[current === 'en' ? 0 : 1] : ru;
}

export function trf(ru: string, vars: Record<string, string | number>): string {
  return tr(ru).replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Число с существительным: формы для 1, 2–4 и 5+ по правилам текущего языка. */
export function trn(n: number, one: string, few: string, many: string): string {
  const d = n % 10;
  const h = n % 100;
  let form = many;
  if (current === 'en') form = n === 1 ? one : many;
  else if (current === 'pl') form = n === 1 ? one : d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
  else form = d === 1 && h !== 11 ? one : d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
  return `${n} ${tr(form)}`;
}
